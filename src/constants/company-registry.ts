const REGIONAL_SUFFIXES = [
  "Express", "Paribahan", "Transport", "Travels", "Service",
  "Enterprise", "Coach", "Lines", "Paribahan Ltd", "Bus Service",
];

const REGIONAL_PREFIXES = [
  "North", "South", "East", "West", "Central", "Metro", "Royal", "Star",
  "City", "Premium", "Golden", "Silver", "Blue", "Green", "Red",
  "Capital", "Highway", "Intercity", "Express", "Border",
];

/** Build a deduplicated list of exactly `targetCount` company names. */
export function buildCompanyRegistry(targetCount = 486): string[] {
  const names = new Set<string>(REGISTERED_COMPANIES);
  let i = 0;
  while (names.size < targetCount) {
    const prefix = REGIONAL_PREFIXES[i % REGIONAL_PREFIXES.length];
    const suffix = REGIONAL_SUFFIXES[Math.floor(i / REGIONAL_PREFIXES.length) % REGIONAL_SUFFIXES.length];
    const num = Math.floor(i / (REGIONAL_PREFIXES.length * REGIONAL_SUFFIXES.length)) + 1;
    names.add(`${prefix} ${suffix}${num > 1 ? ` ${num}` : ""}`);
    i++;
  }
  return Array.from(names).slice(0, targetCount);
}

